import assert from 'node:assert/strict';
import { compareWeaponStats } from '../lib/data-engine/weapon-stat-comparison';
import { resolveLoadout } from '../lib/data-engine/loadout-reader';
import { CURATED_LOADOUTS } from '../lib/data-engine/curated-loadouts';
import { readGenerated } from '../lib/data-engine/generated-reader';

export function runWeaponStatComparisonTests() {
  let passed = 0;
  const eq = (actual: unknown, expected: unknown) => { assert.deepEqual(actual, expected); passed++; };
  const near = (actual: number | null, expected: number) => { assert(actual !== null && Math.abs(actual - expected) < 0.00001, `${actual} != ${expected}`); passed++; };
  const loadout = resolveLoadout(CURATED_LOADOUTS[0]);
  const weapon = (category: string, slug: string) => readGenerated<{ slug: string; stats: Parameters<typeof compareWeaponStats>[0] }>(category).items.find(item => item.slug === slug)!.stats;
  const spectra = compareWeaponStats(weapon('secondary', 'spectra_vandal'), loadout.equipment.secondary.mods);
  const rows = spectra.attacks[0].rows;
  near(rows.criticalChance.after, 57.4);
  near(rows.criticalMultiplier.after, 4.2);
  near(rows.statusChance.after, 84);
  near(rows.attackRate.after, 19.2);
  eq(spectra.coverage, 'PARCIAL');
  const originalMods = structuredClone(loadout.equipment.secondary.mods).map(mod => mod.publishedRank === undefined ? mod : { ...mod, rank: mod.publishedRank });
  near(compareWeaponStats(weapon('secondary', 'spectra_vandal'), originalMods).attacks[0].rows.statusChance.after, 58.8);
  const phantasma = compareWeaponStats(weapon('primary', 'phantasma_prime'), loadout.equipment.primary.mods);
  near(phantasma.attacks[0].rows.statusChance.after, 66.6);
  near(phantasma.attacks[0].rows.attackRate.after, 16.8);
  eq(phantasma.attacks.length, 5);
  eq(phantasma.attacks[1].rows.attackRate.after, null);
  eq(phantasma.attacks[2].rows.attackRate.after, null);
  const glaive = compareWeaponStats(weapon('melee', 'glaive_prime'), loadout.equipment.melee.mods, { melee: true });
  near(glaive.attacks[0].rows.criticalChance.after, 70.4);
  near(glaive.attacks[0].rows.criticalMultiplier.after, 3.7);
  const heavy = glaive.attacks.find(attack => attack.name === 'Charged Throw Recall Explosion')!;
  eq(heavy.rows.criticalChance.before, 26);
  eq(heavy.rows.criticalChance.after, null);
  const burst = compareWeaponStats(weapon('sentinel_weapons', 'burst_laser_prime'), loadout.equipment.companion_weapon.mods);
  near(burst.attacks[0].rows.criticalChance.after, 60);
  near(burst.attacks[0].rows.criticalMultiplier.after, 3.22);
  near(burst.attacks[0].rows.statusChance.after, 42);
  eq(burst.attacks[0].rows.attackRate.after, null);
  const fixture = { attacks: [{ name: 'Normal Attack', crit_chance: 0, crit_mult: 2, status_chance: 10, speed: 5 }], trigger: 'Auto' };
  const conditional = { slug: 'galvanized_shot', name: 'Fixture', rank: 0, maxRank: 0, levelStats: [{ stats: ['+80% Status Chance', 'On Kill:', '+999% Critical Chance'] }] };
  const check = compareWeaponStats(fixture, [conditional]);
  near(check.attacks[0].rows.statusChance.after, 18);
  eq(check.attacks[0].rows.criticalChance.after, 0);
  const unknown = compareWeaponStats(fixture, [{ ...conditional, slug: 'unknown_mod' }]);
  eq(Object.values(unknown.attacks[0].rows).every(row => row.after === null), true);
  const missing = compareWeaponStats({ attacks: [{ name: 'Sem valores', crit_chance: NaN, speed: Infinity }] }, []);
  eq(missing.attacks[0].rows.criticalChance.before, null);
  eq(missing.attacks[0].rows.statusChance.after, null);
  const incomplete = compareWeaponStats(fixture, [{ ...conditional, levelStats: [{ stats: [] }] }]);
  eq(incomplete.attacks[0].rows.statusChance.after, null);
  assert.throws(() => compareWeaponStats(fixture, [{ ...conditional, rank: -1 }]), /nível/); passed++;
  assert.throws(() => compareWeaponStats(fixture, [conditional, conditional]), /repetido/); passed++;
  const fallback = compareWeaponStats({ criticalChance: 0.2, criticalMultiplier: 2, procChance: 0.28, fireRate: 12, trigger: 'Auto' }, []);
  near(fallback.attacks[0].rows.criticalChance.before, 20);
  near(fallback.attacks[0].rows.statusChance.before, 28);
  const snapshot = JSON.stringify(fixture); compareWeaponStats(fixture, []); eq(JSON.stringify(fixture), snapshot);
  console.log(`weapon-stat-comparison: ${passed} verificações passaram`);
  return { passed, failed: 0 };
}
