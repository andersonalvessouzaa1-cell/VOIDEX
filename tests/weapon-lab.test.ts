import assert from 'node:assert/strict';
import { getWeaponIndex, getWeaponDetails } from '../lib/data-engine/weapon-lab-reader';
import { resolveWeaponDraft, isWeaponCategory } from '../lib/data-engine/weapon-lab';
export function runWeaponLabTests() {
  let passed = 0;
  const eq = (a: unknown, b: unknown) => { assert.deepEqual(a, b); passed++; };
  const near = (a: number | null, b: number) => { assert(a !== null && Math.abs(a - b) < 0.00001); passed++; };
  for (const category of ['primary', 'secondary', 'melee', 'sentinel_weapons']) eq(isWeaponCategory(category), true);
  eq(isWeaponCategory('../mods'), false);
  eq(getWeaponIndex('melee').items.some(item => item.type === 'Zaw Component'), false);
  eq(getWeaponIndex('primary').items.some(item => item.slug === 'braton_prime'), true);
  assert.throws(() => getWeaponDetails('primary', 'inexistente'), /Arma/); passed++;
  const { weapon, mods } = getWeaponDetails('secondary', 'spectra_vandal');
  eq(weapon.modGroup, 'Pistol');
  eq(mods.some(mod => mod.name === 'Primed Pistol Gambit'), true);
  eq(mods.some(mod => mod.compatName === 'Shotgun'), false);
  const gambit = mods.find(mod => mod.slug === 'primed_pistol_gambit')!;
  const max = resolveWeaponDraft(weapon, mods, [{ slug: gambit.slug, rank: gambit.maxRank }]);
  near(max.comparison.attacks[0].rows.criticalChance.after, 57.4);
  near(resolveWeaponDraft(weapon, mods, [{ slug: gambit.slug, rank: 0 }]).comparison.attacks[0].rows.criticalChance.after, 23.4);
  eq(max.status, 'NAO_TESTADO');
  assert.throws(() => resolveWeaponDraft(weapon, mods, [{ slug: gambit.slug, rank: -1 }]), /nível/); passed++;
  assert.throws(() => resolveWeaponDraft(weapon, mods, [{ slug: gambit.slug, rank: 11 }]), /nível/); passed++;
  assert.throws(() => resolveWeaponDraft(weapon, mods, [{ slug: gambit.slug, rank: 1 }, { slug: gambit.slug, rank: 2 }]), /repetido/); passed++;
  assert.throws(() => resolveWeaponDraft(weapon, mods, [{ slug: gambit.slug, rank: 10 }, { slug: 'creeping_bullseye', rank: 5 }]), /incompatíveis/); passed++;
  assert.throws(() => resolveWeaponDraft(weapon, mods, [{ slug: 'magnetic_strafe', rank: 3 }]), /compatível|disponível/); passed++;
  assert.throws(() => resolveWeaponDraft(weapon, mods, Array(9).fill({ slug: gambit.slug, rank: 1 })), /oito/); passed++;
  assert.throws(() => resolveWeaponDraft(weapon, mods, null), /Seleção/); passed++;
  const rifle = getWeaponDetails('primary', 'braton_prime');
  const point = rifle.mods.find(mod => mod.name === 'Point Strike')!;
  eq(point.slug, 'point_strike_weaponcritchancemod');
  eq(point.maxRank, 5);
  eq(point.levelStats.at(-1)?.stats[0], '+150% Critical Chance');
  eq(rifle.mods.some(mod => mod.name === 'Serration'), true);
  const speedRifle = rifle.mods.find(mod => mod.name === 'Speed Trigger')!;
  const normalRate = resolveWeaponDraft(rifle.weapon, rifle.mods, []).comparison.attacks[0].rows.attackRate.before!;
  near(resolveWeaponDraft(rifle.weapon, rifle.mods, [{ slug: speedRifle.slug, rank: 5 }]).comparison.attacks[0].rows.attackRate.after, normalRate * 1.6);
  eq(rifle.mods.some(mod => /Beginner|Expert/.test(mod.uniqueName ?? '') && mod.name === 'Point Strike'), false);
  const baseline = resolveWeaponDraft(rifle.weapon, rifle.mods, []);
  const modded = resolveWeaponDraft(rifle.weapon, rifle.mods, [{ slug: point.slug, rank: 5 }]);
  near(modded.comparison.attacks[0].rows.criticalChance.after, baseline.comparison.attacks[0].rows.criticalChance.before! * 2.5);
  const bow = getWeaponDetails('primary', 'paris_prime');
  const speed = bow.mods.find(mod => mod.name === 'Speed Trigger')!;
  eq(resolveWeaponDraft(bow.weapon, bow.mods, [{ slug: speed.slug, rank: 5 }]).comparison.attacks[0].rows.attackRate.after, null);
  const glaive = getWeaponDetails('melee', 'glaive_prime');
  const powerThrow = glaive.mods.find(mod => mod.name === 'Power Throw')!;
  eq(powerThrow.slug, 'power_throw_weaponglaivepowerthrowmod');
  eq(powerThrow.maxRank, 5);
  eq(glaive.mods.some(mod => mod.uniqueName?.includes('/Beginner/')), false);
  const fury = glaive.mods.find(mod => mod.name === 'Fury')!;
  near(resolveWeaponDraft(glaive.weapon, glaive.mods, [{ slug: fury.slug, rank: 5 }]).comparison.attacks[0].rows.attackRate.after, 1.625);
  const source = JSON.stringify(mods); max.mods[0].rank = 0; eq(JSON.stringify(mods), source);
  console.log(`weapon-lab: ${passed} verificações passaram`);
  return { passed, failed: 0 };
}
