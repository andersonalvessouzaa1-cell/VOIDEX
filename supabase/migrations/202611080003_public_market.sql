declare allowed_rank integer; existing_count integer;
begin
 if auth.uid() is null or new.owner_id is distinct from auth.uid() then raise insufficient_privilege using message='Anúncio exige conta proprietária.'; end if;
 if tg_op='INSERT' then
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(new.owner_id::text,0));
  select count(*) into existing_count from public.market_listings where owner_id=new.owner_id;
  if existing_count>=20 then raise check_violation using message='Limite de vinte anúncios por conta.'; end if;
 end if;
 select max_rank into allowed_rank from public.market_items where item_key=new.item_key and enabled;
 if allowed_rank is null or new.item_rank>allowed_rank then raise check_violation using message='Item ou nível não permitido no catálogo.'; end if;
 new.updated_at=pg_catalog.clock_timestamp();
 return new;
end $$;
revoke all on function private_market.guard_listing() from public, anon, authenticated;
create trigger market_listing_guard before insert or update on public.market_listings for each row execute function private_market.guard_listing();
